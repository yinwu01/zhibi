// Optional UI acceptance: PLAYWRIGHT_MODULE and CHROME_PATH can select local runtimes.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const assert = require("node:assert/strict");
const {pathToFileURL} = require("node:url");
const root = path.resolve(__dirname, "..");

(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "zhibi-browser-test-"));
  try {
    const page = await browser.newPage({viewport:{width:1280,height:1000}, deviceScaleFactor:1});
    const requests = [];
    page.on("request", r => {if (r.url().startsWith("http")) requests.push(r.url());});
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root,"examples/report.sample.html")).href);
    await page.screenshot({path:path.join(root,"docs/assets/report-demo.png")});
    assert.equal(await page.locator(".finding").count(), 10);
    await page.locator("summary").first().click();
    assert.ok(await page.locator("details").first().getAttribute("open") !== null);
    assert.equal(requests.length, 0, "Report must not fetch remote resources");
    await page.goto(pathToFileURL(path.join(root,"examples/scan.sample.html")).href);
    assert.ok(await page.locator("#status-title").isVisible());
    assert.ok(await page.locator("#next-title").isVisible());
    assert.ok(await page.locator('.results table').isVisible());
    assert.equal(await page.locator('#evidence').getAttribute('open'),null);
    assert.equal(await page.locator('#identity table').isVisible(),false);
    await page.screenshot({path:path.join(root,"docs/assets/scan-demo.png")});
    await page.locator('#evidence > summary').click();
    assert.ok(await page.locator('#identity table').isVisible());
    assert.equal(requests.length,0,"Enhanced report must open offline");
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path:path.join(root,".preview/report-mobile.png"),fullPage:true});
    await page.goto(pathToFileURL(path.join(root,"examples/learning.html")).href);
    assert.equal(await page.locator(".chapter").count(), 6);
    assert.equal(requests.length,0,"Learning handbook opens offline");
    await page.getByText("看参考答案",{exact:true}).first().click();
    assert.ok(await page.locator(".exercise details").first().getAttribute("open") !== null);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path:path.join(root,".preview/learning-mobile.png"),fullPage:true});
    await page.setViewportSize({width:1280,height:1000});
    await page.evaluate(() => {document.documentElement.style.scrollBehavior = "auto"; scrollTo(0,0);});
    await page.waitForFunction(() => scrollY === 0);
    await page.screenshot({path:path.join(root,".preview/learning-desktop.png")});
    const standalone = path.join(tmp,"start.html");
    fs.copyFileSync(path.join(root,"start.html"),standalone);
    await page.goto(pathToFileURL(standalone).href);
    await page.setViewportSize({width:1160,height:960});
    await page.screenshot({path:path.join(root,"docs/assets/start-demo.png")});
    assert.equal(requests.length,0,"Opening probe must be offline");
    assert.ok(await page.getByRole("heading",{name:/开始检查/}).isVisible());
    await page.getByRole("button",{name:"开始检查",exact:true}).click();
    await page.waitForFunction(() => !document.querySelector("#download").disabled);
    assert.ok(await page.locator("#results").isVisible(),"Readable results must not require Python or JSON export");
    assert.equal(await page.locator(".measurement").count(),4);
    assert.ok(await page.getByRole("heading",{name:"接下来这样做"}).isVisible());
    assert.equal(await page.locator("#next-steps a").count(),3);
    assert.equal(requests.length,0,"Default probe must remain offline");
    let data = JSON.parse(await page.locator("#preview").textContent());
    assert.equal(data.observations[0].facts.automated,true);
    assert.equal(data.observations[1].status,"skipped");
    const reportPromise=page.waitForEvent("download");
    await page.getByRole("button",{name:"保存这份结果",exact:true}).click();
    const reportDownload=await reportPromise;
    const reportFile=path.join(tmp,"result.txt");
    await reportDownload.saveAs(reportFile);
    assert.match(fs.readFileSync(reportFile,"utf8"),/接下来这样做/);
    assert.equal(reportDownload.suggestedFilename(),"zhibi-result.txt");
    await page.route("https://api.ipify.org?format=json", route => route.fulfill({
      status:200,contentType:"application/json",headers:{"Access-Control-Allow-Origin":"*"},body:'{"ip":"198.51.100.10"}'}));
    await page.locator("#network").check();
    await page.getByRole("button",{name:"开始检查",exact:true}).click();
    await page.waitForFunction(() => !document.querySelector("#download").disabled);
    data = JSON.parse(await page.locator("#preview").textContent());
    assert.equal(data.observations[1].status,"ok");
    assert.equal(requests.length,1,"One explicitly enabled request");
    assert.ok(await page.locator("#measurements").getByText("198.51.100.10",{exact:true}).isVisible());
    await page.locator("#advanced > summary").click();
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button",{name:"保存浏览器结果"}).click();
    const download = await downloadPromise;
    const file = path.join(tmp,"browser.json");
    await download.saveAs(file);
    assert.deepEqual(JSON.parse(fs.readFileSync(file)), data);
    await page.unroute("https://api.ipify.org?format=json");
    await page.route("https://api.ipify.org?format=json", route=>route.fulfill({status:503,body:"unavailable"}));
    await page.getByRole("button",{name:"开始检查",exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector("#run").disabled);
    assert.equal(requests.length,2,"Failure must not be retried");
    assert.match(await page.locator("#result-note").textContent(),/IP 没有测成/);
    assert.equal(JSON.parse(await page.locator("#preview").textContent()).observations[1].status,"error");
    assert.equal(await page.locator("#measurements").getByText("198.51.100.10",{exact:true}).count(),0,"Old values must be cleared");
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path:path.join(root,".preview/start-result-mobile.png"),fullPage:true});
    await page.goto(pathToFileURL(path.join(root,".preview/readme.html")).href);
    await page.screenshot({path:path.join(root,".preview/readme-mobile.png"),fullPage:true});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({width:1440,height:1100});
    await page.screenshot({path:path.join(root,".preview/readme-desktop.png"),fullPage:true});
    await page.screenshot({path:path.join(root,".preview/readme-first-screen.png")});
    await page.getByRole("link",{name:"快速开始",exact:true}).click();
    assert.ok(page.url().endsWith("#%E5%BF%AB%E9%80%9F%E5%BC%80%E5%A7%8B"));
    assert.ok(await page.evaluate(() => scrollY > 0));
    assert.deepEqual(errors,[]);
    console.log("UI passed: isolated single HTML, readable results and next steps, text/JSON downloads, opt-in IP, failed IP and no retries, no default requests, desktop/mobile, advanced reports, README navigation.");
  } finally {
    await browser.close();
    fs.rmSync(tmp,{recursive:true,force:true});
  }
})().catch(error => {console.error(error);process.exitCode=1;});
